const UF_SET = new Set(BRAZILIAN_UFS.map((item) => item.uf));

export function isValidUf(value) {
  return UF_SET.has(String(value || "").trim().toUpperCase());
}

export function normalizeUf(value) {
  const uf = String(value || "").trim().toUpperCase();
  return isValidUf(uf) ? uf : null;
}

export function getUfName(uf) {
  const normalized = normalizeUf(uf);
  if (!normalized) return null;
  return BRAZILIAN_UFS.find((item) => item.uf === normalized)?.name ?? null;
}
